// w5d.tech — one-time asset build. Output is committed; runtime needs no Node, no CDN.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const out = path.join(root, 'htdocs/assets/_base');
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });
fs.mkdirSync(path.join(out, 'css'), { recursive: true });

/* 1. Lucide subset: every icon name referenced in views, src, content, config ------------ */
function walk(d, acc = []) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    if (['node_modules', '.git', 'storage', 'htdocs'].includes(f.name)) continue;
    const p = path.join(d, f.name);
    f.isDirectory() ? walk(p, acc) : /\.(php|json|js)$/.test(f.name) && acc.push(p);
  }
  return acc;
}
const names = new Set(['circle']);
const re1 = /icon\(\s*['"]([a-z0-9-]+)['"]/g;
const re2 = /['"]icon['"]\s*[:=]>?\s*['"]([a-z0-9-]+)['"]/g;
const re3 = /['"](?:i|ico)['"]\s*=>\s*['"]([a-z0-9-]+)['"]/g;
for (const f of walk(root)) {
  if (f.includes('/views/static/')) continue;
  const s = fs.readFileSync(f, 'utf8');
  for (const re of [re1, re2, re3]) for (const m of s.matchAll(re)) names.add(m[1]);
}
const iconDir = path.join(here, 'node_modules/lucide-static/icons');
const icons = {}; const missing = [];
for (const n of [...names].sort()) {
  const f = path.join(iconDir, n + '.svg');
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  icons[n] = fs.readFileSync(f, 'utf8').replace(/<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--.*?-->/gs, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(out, 'icons.json'), JSON.stringify(icons));
console.log(`icons: ${Object.keys(icons).length} vendored; missing: ${missing.join(', ') || 'none'}`);

/* 1b. Brand marks (simple-icons subset) for social share + social login ------------------- */
{
  const si = await import('simple-icons');
  const want = { facebook: 'siFacebook', x: 'siX', linkedin: 'siLinkedin', whatsapp: 'siWhatsapp', telegram: 'siTelegram', github: 'siGithub', google: 'siGoogle', instagram: 'siInstagram', youtube: 'siYoutube', reddit: 'siReddit' };
  const brands = {};
  for (const [k, v] of Object.entries(want)) if (si[v]) brands[k] = si[v].path;
  fs.writeFileSync(path.join(out, 'brands.json'), JSON.stringify(brands));
  console.log(`brands: ${Object.keys(brands).join(', ')}`);
}

/* 2. Fonts (self-hosted, latin + arabic subsets only) ------------------------------------ */
const fp = (pkg, file) => path.join(here, 'node_modules/@fontsource-variable', pkg, 'files', file);
const fonts = [
  ['Inter', 'inter', 'inter-latin-wght-normal.woff2', '100 900', 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215'],
  ['Space Grotesk', 'space-grotesk', 'space-grotesk-latin-wght-normal.woff2', '300 700', 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215'],
  ['Noto Sans Arabic', 'noto-sans-arabic', 'noto-sans-arabic-arabic-wght-normal.woff2', '100 900', 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC'],
];
let css = '/* generated by tools/build.mjs — self-hosted fonts, no third-party requests */\n';
for (const [fam, pkg, file, wt, range] of fonts) {
  const dest = file.replace('-normal', '');
  fs.copyFileSync(fp(pkg, file), path.join(out, 'fonts', dest));
  css += `@font-face{font-family:'${fam}';font-style:normal;font-display:swap;font-weight:${wt};src:url(../fonts/${dest}) format('woff2-variations');unicode-range:${range}}\n`;
}
fs.writeFileSync(path.join(out, 'css/fonts.css'), css);

/* 3. Tailwind compile -------------------------------------------------------------------- */
execSync(`npx tailwindcss -c tailwind.config.js -i tailwind.src.css -o ${path.join(out, 'css/tailwind.css')} --minify`, { cwd: here, stdio: 'inherit' });
console.log('tailwind.css written');
